TARGET = "erd_test_roundtrip"


def renamed(db: Database, name: str) -> Database:
    """Kopie der Datenbank unter neuem Namen (FKs innerhalb ziehen mit)."""
    new = copy.deepcopy(db)
    old = new.name
    new.name = name
    for schema in new.schemas:
        for table in schema.tables:
            for fk in table.foreign_keys:
                if fk.referenced_table.database == old:
                    fk.referenced_table = TableRef(name, fk.referenced_table.schema, fk.referenced_table.table)
            table.view_dependencies = [TableRef(name, d.schema, d.table) if d.database == old else d
                                       for d in table.view_dependencies]
    return new


def shape(db: Database):
    """Vergleichbare Gestalt: Spalten, Schlüssel, Indexe, Beziehungen (ohne Datenbanknamen)."""
    tables = {}
    for schema in db.schemas:
        for t in schema.tables:
            cols = [(c.name, c.data_type, c.nullable, c.auto_increment, None if c.auto_increment else c.default, c.comment)
                    for c in t.columns]
            idx = sorted((i.name, i.kind.value, i.columns) for i in t.indexes)
            # Views: Art und benutzte Objekte (eigene Datenbank ohne Namen, fremde mit)
            deps = sorted(("" if d.database == db.name else d.database, d.schema or "", d.table)
                          for d in t.view_dependencies)
            tables[(schema.name, t.name)] = (cols, t.primary_key_columns, idx, t.comment, t.kind.value, deps)
    rels = sorted(
        (r.name, r.child.table, r.parent.table, r.foreign_key.columns, r.identifying, str(r.parent_end), str(r.child_end))
        for r in derive_relationships(Diagram([db]))
    )
    return tables, rels


def keyring_password(user):
    try:
        import keyring

        return keyring.get_password("erd-editor-test", user)
    except Exception:
        return None


def _mysql_family_roundtrip(account: str, port: int, dialect: Dialect = Dialect.MYSQL):
    """Roundtrip für MySQL und MariaDB (gleicher Adapter, anderer Port/keyring-Eintrag)."""
    import pymysql

    from erd_editor.adapters.base import AdapterError
    from erd_editor.adapters.mysql import MySqlAdapter
    from erd_editor.model import ConnectionProfile

    pw = keyring_password(account)
    if pw is None:
        pytest.skip(f"kein Passwort für {account}")
    profile = ConnectionProfile("t", dialect, "localhost", port, "root")
    try:
        with MySqlAdapter(profile, pw) as a:
            if "erd_test_shop" not in a.list_databases():
                pytest.skip("Testschema fehlt")
            original = a.read_database("erd_test_shop")
    except AdapterError as exc:
        pytest.skip(f"Server nicht erreichbar: {exc}")
    conn = pymysql.connect(host="localhost", port=port, user="root", password=pw, autocommit=True)
    try:
        with conn.cursor() as cur:
            cur.execute(f"DROP DATABASE IF EXISTS {TARGET}")
            for statement in generate_statements(renamed(original, TARGET)):
                cur.execute(statement)
        with MySqlAdapter(profile, pw) as a:
            copy_db = a.read_database(TARGET)
    finally:
        with conn.cursor() as cur:
            cur.execute(f"DROP DATABASE IF EXISTS {TARGET}")
        conn.close()
    return original, copy_db


def _mysql_roundtrip():
    return _mysql_family_roundtrip("root", 3306)


def _mariadb_roundtrip():
    return _mysql_family_roundtrip("root@mariadb", 3307, Dialect.MARIADB)


def _postgres_roundtrip():
    import psycopg

    from erd_editor.adapters.postgres import PostgresAdapter
    from erd_editor.model import ConnectionProfile

    pw = keyring_password("postgres")
    if pw is None:
        pytest.skip("kein PostgreSQL-Passwort")
    profile = ConnectionProfile("t", Dialect.POSTGRESQL, "localhost", None, "postgres")
    with PostgresAdapter(profile, pw) as a:
        if "erd_test_shop" not in a.list_databases():
            pytest.skip("Testschema fehlt")
        original = a.read_database("erd_test_shop")
    admin = psycopg.connect(host="localhost", user="postgres", password=pw, dbname="postgres", autocommit=True)
    try:
        admin.execute(f"DROP DATABASE IF EXISTS {TARGET} WITH (FORCE)")
        admin.execute(f"CREATE DATABASE {TARGET} ENCODING 'UTF8' TEMPLATE template0")
        with psycopg.connect(host="localhost", user="postgres", password=pw, dbname=TARGET, autocommit=True) as conn:
            for statement in generate_statements(renamed(original, TARGET)):
                if not statement.startswith("--"):
                    conn.execute(statement)
        with PostgresAdapter(profile, pw) as a:
            copy_db = a.read_database(TARGET)
    finally:
        admin.execute(f"DROP DATABASE IF EXISTS {TARGET} WITH (FORCE)")
        admin.close()
    return original, copy_db


def _mssql_roundtrip():
    from erd_editor.adapters.base import AdapterError
    from erd_editor.adapters.mssql import MssqlAdapter, connection_string
    from erd_editor.model import ConnectionProfile

    import pyodbc

    profile = ConnectionProfile("t", Dialect.MSSQL, "localhost", None, None, {"auth": "windows"})
    try:
        with MssqlAdapter(profile) as a:
            if "erd_test_shop" not in a.list_databases():
                pytest.skip("Testschema fehlt")
            original = a.read_database("erd_test_shop")
            driver = a.driver()
    except AdapterError as exc:
        pytest.skip(f"SQL Server nicht erreichbar: {exc}")
    conn = pyodbc.connect(connection_string(profile, None, "master", driver), autocommit=True)
    drop = (f"IF DB_ID('{TARGET}') IS NOT NULL BEGIN ALTER DATABASE {TARGET} SET SINGLE_USER WITH ROLLBACK IMMEDIATE; "
            f"DROP DATABASE {TARGET}; END")
    try:
        cur = conn.cursor()
        cur.execute(drop)
        for statement in generate_statements(renamed(original, TARGET)):
            if not statement.startswith("--"):
                cur.execute(statement)
        cur.execute("USE master")
        with MssqlAdapter(profile) as a:
            copy_db = a.read_database(TARGET)
    finally:
        conn.cursor().execute("USE master")
        conn.cursor().execute(drop)
        conn.close()
    return original, copy_db


@pytest.mark.parametrize("roundtrip", [_mysql_roundtrip, _mariadb_roundtrip, _postgres_roundtrip, _mssql_roundtrip],
                         ids=["mysql", "mariadb", "postgresql", "mssql"])
def test_roundtrip_against_real_server(roundtrip):
    """Skript erzeugen, ausführen, wieder einlesen: dasselbe Schema."""
    original, copy_db = roundtrip()
    expected_tables, expected_rels = shape(original)
    got_tables, got_rels = shape(copy_db)
    for key, value in expected_tables.items():
        assert got_tables.get(key) == value, key
    assert set(got_tables) == set(expected_tables)
    assert got_rels == expected_rels
    assert copy_db.charset == original.charset or original.dialect is not Dialect.MYSQL


