def test_foreign_keys_come_last(test_schema):
    statements = generate_statements(test_schema.database("shop"))
    first_fk = next(i for i, s in enumerate(statements) if "FOREIGN KEY" in s)
    assert all("FOREIGN KEY" in s for s in statements[first_fk:])
    assert sum("CREATE TABLE" in s for s in statements) == 9


