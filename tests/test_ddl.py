class TestDialog:
    def test_preview_follows_selection_and_options(self, qapp, test_schema):
        from erd_editor.ui.sql_dialog import SqlExportDialog

        d = SqlExportDialog(test_schema, ["shop"])
        assert d.selected() == ["shop"]
        assert "CREATE TABLE `kunde`" in d.preview.toPlainText()
        assert "`land`" not in d.preview.toPlainText().split("REFERENCES")[0]  # stammdaten nicht gewählt
        assert not hasattr(d, "drop_existing") and "DROP" not in d.preview.toPlainText()
        d.comments.setChecked(False)
        assert "COMMENT" not in d.preview.toPlainText()
        for i in range(d.databases.count()):
            d.databases.item(i).setCheckState(Qt.CheckState.Unchecked)
        assert "mindestens eine Datenbank" in d.preview.toPlainText()

    def test_save_and_copy(self, qapp, test_schema, tmp_path):
        from PySide6.QtGui import QGuiApplication

        from erd_editor.ui.sql_dialog import SqlExportDialog

        d = SqlExportDialog(test_schema, ["shop"], tmp_path)
        assert d.suggested_path() == tmp_path / "shop.sql"
        d.save(str(tmp_path / "shop.sql"))
        assert (tmp_path / "shop.sql").read_text(encoding="utf-8").startswith("-- Erzeugt mit")
        d.copy_to_clipboard()
        assert "CREATE TABLE" in QGuiApplication.clipboard().text()

    def test_main_window_preselects_models(self, qapp, test_schema, monkeypatch):
        from erd_editor.main import MainWindow
        from erd_editor.ui.sql_dialog import SqlExportDialog

        seen = []
        monkeypatch.setattr(SqlExportDialog, "exec", lambda d: seen.append(d.selected()) or 0)
        w = MainWindow()
        w.load_diagram(test_schema)
        w.sql_export_dialog()
        assert seen[-1] == ["shop", "stammdaten"]  # keine Modelle: alle
        w.take_over("stammdaten")
        w.sql_export_dialog()
        assert seen[-1] == ["stammdaten"]  # Modelle vorausgewählt
        w.setWindowModified(False)
        w.close()


@pytest.mark.parametrize("dialect", list(Dialect))
def test_checks_in_create_table(dialect):
    from erd_editor.model import CheckConstraint

    d = _modeled(dialect)
    schema = None if dialect.mysql_family else "lager"
    regal = d.find_table(TableRef("lager", schema, "regal"))
    fach = d.find_table(TableRef("lager", schema, "fach"))
    regal.columns.append(Column("hoehe", "int"))
    fach.columns.append(Column("hoehe", "int"))
    regal.checks.append(CheckConstraint("ck_hoehe", "hoehe > 0", ("hoehe",)))
    fach.checks.append(CheckConstraint("ck_hoehe", "hoehe BETWEEN 1 AND 9", ("hoehe",)))
    fach.checks.append(CheckConstraint("ck_leer", "  ", ()))
    script = generate_script(d)
    q = lambda n: quote(dialect, n)  # noqa: E731
    assert f"CONSTRAINT {q('ck_hoehe')} CHECK (hoehe > 0)" in script
    # Namen sind (je Schema) eindeutig, leere Ausdrücke entfallen
    assert f"CONSTRAINT {q('ck_hoehe_2')} CHECK (hoehe BETWEEN 1 AND 9)" in script
    assert "ck_leer" not in script
    assert ("MySQL 8.0.16" in script) == (dialect is Dialect.MYSQL)
    assert script.count("MySQL 8.0.16") <= 1
