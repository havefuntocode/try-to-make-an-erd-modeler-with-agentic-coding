def test_quote():
    assert quote(Dialect.MYSQL, "a`b") == "`a``b`"
    assert quote(Dialect.POSTGRESQL, 'a"b') == '"a""b"'
    assert quote(Dialect.MSSQL, "a]b") == "[a]]b]"


def test_literal():
    assert literal("O'Neil") == "'O''Neil'"
    assert literal("Ä", Dialect.MSSQL) == "N'Ä'"


