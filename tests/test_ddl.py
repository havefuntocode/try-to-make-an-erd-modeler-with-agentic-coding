def test_on_delete_rules(test_schema):
    pos = test_schema.find_table(TableRef("shop", None, "bestellposition"))
    next(fk for fk in pos.foreign_keys if fk.name == "fk_pos_bestellung").on_delete = "CASCADE"
    script = generate_script(test_schema, ["shop"])
    assert "REFERENCES `shop`.`bestellung` (`id`) ON DELETE CASCADE" in script
    assert "ON DELETE NO ACTION" not in script and "ON DELETE RESTRICT" not in script  # Standard wird weggelassen


def _modeled(dialect):
    d = add_database(Diagram(), "lager", dialect, None if dialect.mysql_family else "lager")
    schema = None if dialect.mysql_family else "lager"
    ref = lambda t: TableRef("lager", schema, t)  # noqa: E731
    from erd_editor.model import Index, IndexKind

    id_type = ID_TYPES[dialect]
    for name in ("regal", "fach"):
        d = add_table(d, ref(name), Table(name, [Column("id", id_type, False, auto_increment=True)],
                                          [Index("PRIMARY", IndexKind.PRIMARY, ("id",))]))
    d, _ = add_relationship(d, ref("fach"), ref("regal"), identifying=True)
    return d


@pytest.mark.parametrize("dialect", list(Dialect))
def test_modeled_database_per_dialect(dialect):
    script = generate_script(_modeled(dialect))
    assert "fk_fach_regal" in script and "regal_id" in script
    if dialect is Dialect.POSTGRESQL:
        assert "GENERATED BY DEFAULT AS IDENTITY" in script
        assert '"fach_pkey"' in script  # „PRIMARY“ wäre in PostgreSQL nicht eindeutig
        assert 'CREATE SCHEMA "lager"' in script
    if dialect is Dialect.MSSQL:
        assert "IDENTITY(1,1)" in script and "\nGO\n" in script
    if dialect.mysql_family:
        assert "AUTO_INCREMENT" in script and "`fach`" in script


